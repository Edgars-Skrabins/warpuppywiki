import { describe, expect, it } from "vitest";
import type { CategoryDiff } from "../diff/types";
import { toMarkdown } from "./markdown";

const weapons: CategoryDiff = {
  id: "weapons",
  label: "Weapons",
  counts: { added: 2, removed: 1, changed: 2 },
  notes: [],
  entities: [
    {
      key: "weapon:bow",
      name: "Compound Bow",
      status: "changed",
      changes: [
        { path: "muzzleVelocity", kind: "changed", before: 90, after: 95 },
        { path: "effectiveRange", kind: "changed", before: 60, after: 70 },
      ],
    },
    { key: "weapon:m14", name: "M14", status: "added", changes: [] },
    {
      key: "weapon:ak74",
      name: "AK74",
      status: "changed",
      changes: [
        { path: "suppressionMultiplier", kind: "added", after: 1.05 },
        { path: "fireModes[]", kind: "added", after: "Burst" },
        { path: "fireModes[]", kind: "removed", before: "Single" },
        { path: "unlock.level", kind: "changed", before: 3, after: 5 },
      ],
    },
    { key: "weapon:bizon", name: "PP-19 Bizon", status: "added", changes: [] },
    { key: "weapon:svd", name: "SVD", status: "removed", changes: [] },
  ],
};

const damage: CategoryDiff = {
  id: "damage",
  label: "Damage rules",
  counts: { added: 0, removed: 0, changed: 1 },
  notes: [],
  entities: [
    {
      key: "rule:infantry|bone",
      name: "Infantry · Bone",
      status: "changed",
      changes: [{ path: "amount", kind: "changed", before: -75, after: -50 }],
    },
  ],
};

const empty: CategoryDiff = {
  id: "loot",
  label: "Loot tables",
  counts: { added: 0, removed: 0, changed: 0 },
  notes: [],
  entities: [],
};

describe("toMarkdown", () => {
  it("writes every category with changes", () => {
    expect(toMarkdown([weapons, empty, damage], { from: "25677108", to: "25937608" })).toBe(
      [
        "## Wardogs data changes: build 25677108 → 25937608",
        "",
        "### Weapons",
        "",
        "**Added:** M14, PP-19 Bizon",
        "",
        "**Removed:** SVD",
        "",
        "- **Compound Bow:** muzzle velocity 90 → 95 m/s (buff); effective range 60 → 70 m (buff)",
        "- **AK74:** suppression multiplier added: 1.05; +1 fire mode, −1 fire mode; unlock level 3 → 5 (nerf)",
        "",
        "### Damage rules",
        "",
        "- **Infantry · Bone:** amount −75 → −50 (more damage to infantry)",
        "",
        "_Generated by warpuppywiki from warpuppies/wardogs-data. Unofficial; numbers from the game files._",
        "",
      ].join("\n"),
    );
  });

  it("limits the output to the given categories", () => {
    const text = toMarkdown([weapons, damage], { from: "1", to: "2", categories: ["damage"] });
    expect(text).not.toContain("### Weapons");
    expect(text).toContain("### Damage rules");
  });

  it("keeps a multi-line text change on its entity's line", () => {
    const ammo: CategoryDiff = {
      id: "ammo",
      label: "Ammunition",
      counts: { added: 0, removed: 0, changed: 1 },
      notes: [],
      entities: [
        {
          key: "projectile:35mm",
          name: "35x228mm",
          status: "changed",
          changes: [{ path: "description", kind: "changed", before: "Rounds\nOptimised", after: "Rounds\nOptimized" }],
        },
      ],
    };
    expect(toMarkdown([ammo], { from: "1", to: "2" })).toContain(
      "- **35x228mm:** description Rounds Optimised → Rounds Optimized\n",
    );
  });
});
